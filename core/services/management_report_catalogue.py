def get_management_report_catalogue():
    """Return a fresh serializable catalogue for UI/API consumers."""
    return {
        "version": CATALOGUE_VERSION,
        "categories": [
            {
                **category,
                "metrics": [dict(metric, breakdowns=list(metric["breakdowns"])) for metric in category["metrics"]],
            }
            for category in METRIC_CATALOGUE
        ],
    }


def get_management_report_metric(metric_id):
    """Return a metric definition by stable ID, or None when unsupported."""
    for category in METRIC_CATALOGUE:
        for metric in category["metrics"]:
            if metric["id"] == metric_id:
                return {**metric, "category_id": category["id"], "category_label": category["label"]}
    return None
